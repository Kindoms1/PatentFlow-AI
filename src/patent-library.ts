/**
 * 专利分类与撰写知识库（patent-library）。
 *
 * 作用：
 *   1. 技术领域分类：每个领域给出常用 IPC 大组/小类、常见保护主题、权利要求布局、说明书/实施例/附图撰写要点和常见缺陷；
 *   2. 领域识别：根据交底材料、发明点和事实，用关键词与 IPC 号命中给出最可能的技术领域（detectDomain）；
 *   3. 提示词注入：把识别出的领域撰写要点整理成一段指引（domainGuide），供 /发明稿 与对话技能使用；
 *   4. 知识库条目：领域指引、虚构示范样例、真实参考资料三类条目，供“专利分类与样例”页面检索、预览、下载 Word、加入对话。
 *
 * 资料纪律：
 *   - REAL_REFERENCES 只收录 docs/references 下实际存在的公告文本和 CNIPA 材料，记录公开号、标题、来源和用途；
 *     只归纳其章节结构与写法特征，不复制受保护的正文内容。
 *   - LIBRARY_SAMPLES 全部为虚构示范，fictional 恒为 true，不带任何公开号，不对应任何真实专利或申请。
 *   - IPC 类名为便于阅读的简称，正式分类以国家知识产权局使用的现行 IPC 版本和审查部门的分类为准。
 *
 * 本模块不依赖 model.ts，避免循环引用；model.ts 通过 libraryDoc() 把条目放进对话队列。
 */

