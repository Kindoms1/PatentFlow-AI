/** 根据独立权利要求开头判断其主题类型。 */
export function claimKindOf(text: string): ClaimKind {
  const head = text.replace(/\s+/g, "").slice(0, 60);
  if (/存储介质|可读介质|程序产品/.test(head)) return "介质";
  if (/(?:在|于)制备.{0,30}(?:中|上)的(?:用途|应用)|的用途|的应用/.test(head)) return "用途";
  if (/制备方法|合成方法|生产方法|制造方法|加工方法/.test(head)) return "制备方法";
  if (/电子设备|计算机设备|终端设备|网络设备|服务器|控制器|芯片/.test(head)) return "设备";
  if (/方法/.test(head)) return "方法";
  if (/组合物|制剂|配方|涂料|浆料/.test(head)) return "组合物";
  if (/化合物|药学上可接受的盐/.test(head)) return "化合物";
  if (/装置|系统|设备|机构|组件|模块|器|仪|机(?:[，,]|$)/.test(head)) return "装置";
  return "产品";
}

export interface SubjectCoverage {
  ok: boolean;
  covered: ClaimKind[];
  expected: ClaimKind[];
  missing: ClaimKind[];
  detail: string;
}

/** 按领域判断独立权利要求的主题布局是否合理。 */
export function subjectCoverage(domain: TechDomain, independentTexts: string[]): SubjectCoverage {
  const kinds = [...new Set(independentTexts.map(claimKindOf))];
  const normalized = new Set<ClaimKind>(kinds);
  // 产品与装置、组合物与产品在部分领域可以互相替代。
  if (normalized.has("装置")) normalized.add("产品");
  if (normalized.has("组合物")) normalized.add("产品");
  const covered = domain.claimKinds.filter((kind) => normalized.has(kind));
  const missing = domain.claimKinds.filter((kind) => !normalized.has(kind));
  const primary = domain.claimKinds[0];
  const primaryOk = normalized.has(primary) || (primary === "装置" && normalized.has("产品")) || (primary === "化合物" && normalized.has("组合物"));
  const ok = independentTexts.length > 0 && primaryOk && covered.length >= domain.minClaimKinds;
  const detail = independentTexts.length
    ? `已覆盖：${kinds.join("、")}；${domain.name}通常覆盖${domain.claimKinds.join("、")}（至少 ${domain.minClaimKinds} 类，首选${primary}）`
    : "没有独立权利要求";
  return { ok, covered, expected: domain.claimKinds, missing, detail };
}

