/** 生成注入撰写提示词的领域指引。 */
export function domainGuide(domain: TechDomain, detection?: DomainDetection): string {
  const lines: string[] = [];
  const basis = detection && detection.hits.length ? `（识别依据：${detection.hits.slice(0, 6).join("、")}${detection.confident ? "" : "；把握不高，请结合材料判断"}）` : "";
  lines.push(`【技术领域】${domain.name}${basis}`);
  if (domain.ipc.length) {
    lines.push(`【参考 IPC】${domain.ipc.map((item) => `${item.code} ${item.label}`).join("；")}。仅供检索和撰写参考，不要写进申请文件正文，正式分类由审查部门确定。`);
  }
  lines.push(`【常见保护主题】${domain.subjects.join("；")}`);
  lines.push(`【独立权利要求主题】通常覆盖：${domain.claimKinds.join("、")}（至少 ${domain.minClaimKinds} 类，首选${domain.claimKinds[0]}）。按发明的实际客体取舍，不要为凑主题写出没有说明书支持的权利要求。`);
  lines.push(`【权利要求布局】\n${domain.claimPlan.map((item, index) => `${index + 1}. ${item}`).join("\n")}`);
  lines.push(`【说明书要点】\n${domain.writingPoints.map((item, index) => `${index + 1}. ${item}`).join("\n")}`);
  lines.push(`【实施例要点】\n${domain.embodimentPoints.map((item, index) => `${index + 1}. ${item}`).join("\n")}`);
  lines.push(`【附图要点】\n${domain.figurePoints.map((item, index) => `${index + 1}. ${item}`).join("\n")}`);
  if (domain.usesReferenceNumerals) {
    lines.push("【附图标记】本领域属于结构类：权利要求和具体实施方式中每个部件第一次出现时写附图标记，例如“底座(1)”；具体实施方式最后用“### 附图标记”列出全部标记，编号与附图说明一致。");
  }
  lines.push(`【常见缺陷，撰写时主动避免】\n${domain.pitfalls.map((item, index) => `${index + 1}. ${item}`).join("\n")}`);
  return lines.join("\n");
}

/** 对话技能（挖点、交底）用的简短领域提示。 */
export function domainHint(detection: DomainDetection): string {
  // A guess from a few keywords misleads more than it helps (an English paper once read as "电池与储能"): only a confident detection becomes a hint.
  if (detection.domain.id === "general" || !detection.confident) return "";
  const domain = detection.domain;
  return `【技术领域参考】${domain.name}（参考 IPC：${domain.ipc.slice(0, 3).map((item) => item.code).join("、")}）。挖点和确认保护主题时考虑本领域常见主题：${domain.subjects.slice(0, 4).join("；")}。该判断来自关键词，如与材料不符以材料为准。`;
}

