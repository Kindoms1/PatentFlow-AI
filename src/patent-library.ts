// 领域识别

/** 这些领域是应用场景；与软件/AI 同时命中时优先于软件/AI。 */
const APPLICATION_FIRST = new Set<DomainId>(["agriculture"]);

const IPC_IN_TEXT = /\b([A-H]\d{2}[A-Z])\s*(\d{1,4}\s*\/\s*\d{1,6})?/g;

function countOccurrences(haystack: string, needle: string, cap: number): number {
  if (!needle) return 0;
  let count = 0;
  let from = 0;
  const lowerNeedle = needle.toLowerCase();
  const asciiWord = /^[a-z0-9]/.test(lowerNeedle) && /[a-z0-9]$/.test(lowerNeedle) && /^[\x00-\x7f]+$/.test(lowerNeedle);
  while (count < cap) {
    const index = haystack.indexOf(lowerNeedle, from);
    if (index === -1) break;
    from = index + lowerNeedle.length;
    // Latin keywords (SOC, BMS, PWM) must stand alone: "SOC" inside "associated" once made an English remote-sensing paper read as battery storage.
    if (asciiWord && (/[a-z0-9]/.test(haystack[index - 1] ?? "") || /[a-z0-9]/.test(haystack[from] ?? ""))) continue;
    count += 1;
  }
  return count;
}

/**
 * 根据文本识别技术领域。关键词每个最多计 3 次；文本中出现的 IPC 小类按 4 分计。
 * 得分低于 3 或者没有领先第二名时 confident 为 false，调用方应把领域作为参考而非结论。
 */
export function detectDomain(text: string): DomainDetection {
  const haystack = (text || "").toLowerCase();
  const ipcInText = new Set<string>();
  for (const match of (text || "").toUpperCase().matchAll(IPC_IN_TEXT)) ipcInText.add(match[1]);

  const scored = TECH_DOMAINS.filter((domain) => domain.id !== "general").map((domain) => {
    const hits: Array<{ term: string; weight: number }> = [];
    for (const keyword of domain.keywords) {
      const count = countOccurrences(haystack, keyword, 3);
      if (count) hits.push({ term: keyword, weight: count * (domain.keywordWeight ?? 1) });
    }
    for (const item of domain.ipc) {
      if (ipcInText.has(item.code)) hits.push({ term: item.code, weight: 4 });
    }
    hits.sort((a, b) => b.weight - a.weight);
    const score = hits.reduce((sum, hit) => sum + hit.weight, 0);
    return { domain, score, hits: hits.map((hit) => hit.term) };
  });
  scored.sort((a, b) => b.score - a.score);
  // “模型、算法”是技术手段，不是应用领域：明确命中农业等应用领域时，以应用领域为主。
  if (scored[0]?.domain.id === "software-ai") {
    const applied = scored.findIndex((item) => APPLICATION_FIRST.has(item.domain.id) && item.score >= 4);
    if (applied > 0) scored.unshift(...scored.splice(applied, 1));
  }

  const best = scored[0];
  const second = scored[1];
  if (!best || best.score < 3) {
    return {
      domain: getDomain("general"),
      score: best?.score ?? 0,
      hits: best?.hits.slice(0, 8) ?? [],
      runnerUp: best && best.score > 0 ? { domain: best.domain, score: best.score } : null,
      confident: false,
    };
  }
  const confident = best.score >= 4 && (!second || best.score >= second.score * 1.25);
  return {
    domain: best.domain,
    score: best.score,
    hits: best.hits.slice(0, 8),
    runnerUp: second && second.score > 0 ? { domain: second.domain, score: second.score } : null,
    confident,
  };
}

/** 识别结果的一句话说明，用于对话中的过程提示。 */
export function detectionNote(result: DomainDetection): string {
  if (result.domain.id === "general") {
    return result.runnerUp
      ? `技术领域暂不确定（最接近：${result.runnerUp.domain.name}），按通用撰写要点处理。`
      : "材料中没有足够的领域线索，按通用撰写要点处理。";
  }
  const ipc = result.domain.ipc.slice(0, 3).map((item) => item.code).join("、");
  const basis = result.hits.slice(0, 5).join("、");
  const second = !result.confident && result.runnerUp ? `；也可能属于${result.runnerUp.domain.name}` : "";
  return `识别技术领域：${result.domain.name}（依据：${basis}；参考 IPC：${ipc}${second}）。`;
}

