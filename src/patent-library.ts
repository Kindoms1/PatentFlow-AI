/** 独立权利要求的主题类型。“装置”同时涵盖装置与系统。 */
export type ClaimKind = "方法" | "装置" | "设备" | "介质" | "产品" | "组合物" | "化合物" | "制备方法" | "用途";

export interface IpcCode {
  /** 小类或大组，例如 G06T、A61B 5/00。 */
  code: string;
  /** 类名简称，正式类名以现行 IPC 版本为准。 */
  label: string;
}

export interface TechDomain {
  id: DomainId;
  name: string;
  summary: string;
  ipc: IpcCode[];
  /** 识别用关键词：命中越多越可能是该领域。 */
  keywords: string[];
  /** 关键词每次命中的权重，默认 1。应用场景词很具体的领域可以调高。 */
  keywordWeight?: number;
  /** 该领域常见的保护主题（可以写成独立权利要求的客体）。 */
  subjects: string[];
  /** 独立权利要求通常应覆盖的主题类型。 */
  claimKinds: ClaimKind[];
  /** claimKinds 中至少覆盖几类才算布局合理。 */
  minClaimKinds: number;
  /** 权利要求布局建议。 */
  claimPlan: string[];
  /** 说明书撰写要点。 */
  writingPoints: string[];
  /** 具体实施方式/实施例要点。 */
  embodimentPoints: string[];
  /** 附图要点。 */
  figurePoints: string[];
  /** 该领域代理人审核时常见的问题。 */
  pitfalls: string[];
  /** 结构类领域：权利要求和说明书中的部件应带附图标记。 */
  usesReferenceNumerals: boolean;
}

export interface RealReference {
  id: string;
  /** 公开号/授权公告号；CNIPA 材料没有公开号时为空字符串。 */
  pn: string;
  title: string;
  kind: "授权发明" | "官方材料";
  /** 扉页可读出的 IPC；文本层读不出时不填，以公告文本为准。 */
  ipc: string[];
  domainIds: DomainId[];
  /** 公开网页地址；没有核实过的地址不填。 */
  url: string;
  /** 项目内本地文件，相对项目根目录。 */
  localPath: string;
  /** 只记录可以从文件中核实的结构特征。 */
  structure: string[];
  /** 在 PatentFlow 中的用途说明。 */
  use: string;
}

export interface LibrarySample {
  id: string;
  domainId: DomainId;
  title: string;
  summary: string;
  /** 恒为 true：示范样例是虚构的。 */
  fictional: true;
  /** 与 /发明稿 输出相同的 Markdown 结构，可直接按申请文件格式导出。 */
  markdown: string;
}

export type LibraryEntryKind = "domain" | "sample" | "reference";

export interface LibraryEntry {
  id: string;
  kind: LibraryEntryKind;
  title: string;
  subtitle: string;
  domainIds: DomainId[];
  ipc: string[];
  /** 预览与加入对话用的纯文本（Markdown）。 */
  text: string;
  fictional: boolean;
}

export interface DomainDetection {
  domain: TechDomain;
  /** 归一化前的命中得分。 */
  score: number;
  /** 命中的关键词或 IPC 号，按得分从高到低。 */
  hits: string[];
  /** 第二可能的领域，没有则为 null。 */
  runnerUp: { domain: TechDomain; score: number } | null;
  /** 得分足够高且明显领先第二名。 */
  confident: boolean;
}

