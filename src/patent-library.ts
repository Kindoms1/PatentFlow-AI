/** 关键词检索：空格分隔的每个词都要命中标题、副标题、IPC 或正文；IPC 按前缀筛选。 */
export function searchLibrary(query: string, filter: LibraryFilter = {}): LibraryEntry[] {
  const tokens = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  const ipc = (filter.ipc ?? "").trim().toUpperCase().replace(/\s+/g, "");
  return libraryEntries().filter((entry) => {
    if (filter.kind && filter.kind !== "all" && entry.kind !== filter.kind) return false;
    if (filter.domainId && filter.domainId !== "all" && !entry.domainIds.includes(filter.domainId as DomainId)) return false;
    if (ipc && !entry.ipc.some((code) => code.toUpperCase().replace(/\s+/g, "").startsWith(ipc))) return false;
    if (!tokens.length) return true;
    const haystack = `${entry.title}\n${entry.subtitle}\n${entry.ipc.join(" ")}\n${entry.text}`.toLowerCase();
    return tokens.every((token) => haystack.includes(token));
  });
}

export function findLibraryEntry(id: string): LibraryEntry | null {
  return libraryEntries().find((entry) => entry.id === id) ?? null;
}

export function findSample(entryId: string): LibrarySample | null {
  return LIBRARY_SAMPLES.find((sample) => `lib-${sample.id}` === entryId || sample.id === entryId) ?? null;
}

